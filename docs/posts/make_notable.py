"""
make_notable.py -- the "Notable Activity" share card from a JSON spec.

    python docs/posts/make_notable.py docs/posts/notable/2026-10-19.json
    python docs/posts/render_post.py docs/posts/2026-10-19-notable.html

The spec is usually started by probe_notable.py (repo root), which fills the
numbers (spots, directional delta per ticker, the biggest contracts with their
side, size and premium) and leaves the WORDS empty: headline, sub, per-row
notes and the read are written by hand from what the numbers show. Keys:

  date, kicker, h1, sub                      header
  tiles      [[value, label], ...]           up to 4
  bars_title, bars_sub, bars_max             the per-ticker chart
  bars       [{label, v, text}, ...]         v = magnitude (abs), text = signed label
  trades     [{d, k, side, chip, n, prem, note, pend}]  card.js tradeTable rows;
             d = ticker, pend = "TUE" etc. (the session whose OI confirms it)
  confirm    legend text for the pend chip
  read, mon  the read box (mon = small print under it)
"""
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TPL = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=1080">
<title>Notable Activity {date}</title>
<!-- Share card (README.md), generated by make_notable.py from {spec}. Data: Unusual Whales API. -->
<link rel="stylesheet" href="card.css"></head>
<body>
<div class="wrap">
  <div class="kicker">{kicker}</div>
  <h1>{h1}</h1>
  <div class="sub">{sub}</div>
  <div class="tiles">{tiles}</div>
  <div class="card">
    <h2>{bars_title}</h2>
    <div class="h2s">{bars_sub}</div>
    <svg id="bars" width="946" height="{bars_h}" role="img" aria-label="{bars_title}"></svg>
  </div>
  <div class="card">
    <h2>Notable activity</h2>
    <div class="h2s">Biggest contracts by premium · side read from ask/bid · multi-leg packages read as one trade</div>
    <table class="trades" id="tt"></table>
    <div class="legend"><span><span class="chip b">BOUGHT</span> at the ask</span><span><span class="chip s">SOLD</span> at the bid</span>
      <span><span class="chip x">SPREAD</span> both sides</span><span><span class="chip pend">{pend}</span> {confirm}</span></div>
  </div>
  <div class="read">{read}<span class="mon">{mon}</span></div>
</div>
<div class="foot">
  <span>Data: Unusual Whales API · method: <b>probe_notable.py</b> · not financial advice</span>
  <span><span class="repo">github.com/levijon2623/WeBullRG</span> · analysis with Claude (Anthropic)</span>
</div>
<script src="card.js"></script>
<script>
compareBars(document.getElementById('bars'), {bars}, {bars_max}, {{x0: 80, H: 22, gap: 10}});
tradeTable(document.getElementById('tt'), {trades});
</script>
</body></html>
"""


def main(path):
    spec = json.load(open(path, encoding="utf-8"))
    tiles = "".join(f'<div class="tile"><div class="v num">{html.escape(v)}</div>'
                    f'<div class="l">{html.escape(l)}</div></div>' for v, l in spec["tiles"])
    pend = next((t.get("pend") for t in spec["trades"] if isinstance(t.get("pend"), str)), "TUE")
    for b in spec["bars"]:              # polarity by sign: bearish = the "sold" red, bullish = the "bought" blue
        b.setdefault("color", "#e66767" if str(b.get("text", "")).lstrip()[:1] in ("−", "-") else "#3987e5")
    out = TPL.format(date=spec["date"], spec=os.path.basename(path), kicker=spec["kicker"], h1=spec["h1"],
                     sub=spec["sub"], tiles=tiles, bars_title=spec["bars_title"], bars_sub=spec["bars_sub"],
                     bars_h=len(spec["bars"]) * 32 + 4, bars=json.dumps(spec["bars"]), bars_max=spec["bars_max"],
                     trades=json.dumps(spec["trades"]), pend=pend,
                     confirm=spec.get("confirm", "confirmed by the next session's open interest"),
                     read=spec["read"], mon=spec.get("mon", ""))
    dst = os.path.join(HERE, f"{spec['date']}-notable.html")
    open(dst, "w", encoding="utf-8").write(out)
    print("wrote", dst)


if __name__ == "__main__":
    main(sys.argv[1])
